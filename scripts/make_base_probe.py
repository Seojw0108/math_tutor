def build() -> list[dict]:
    rows = []
    for (sid, std, sname, area, grade, mid, style, slang, q, ans, wrong, ctx, kws, turns) in S:
        msgs = [{"role": "system", "content": build_system(grade, sname)},
                {"role": "user", "content": LESSON_START}]
        for t, c, rt in turns:
            msgs.append({"role": "assistant", "content": t})
            msgs.append({"role": "user", "content": c, "response_type": rt})
        msgs[-1]["expected_answer"] = ans
        rows.append({
            "id": sid, "standard": std, "standard_name": sname, "area": area, "grade_band": grade,
            "misconception_id": mid, "student_persona": {"style": style, "slang": slang},
            "problem": {"question": q, "answer": ans, "wrong_answer": wrong, "context": ctx},
            "diag_keywords": kws, "messages": msgs, "split": "probe",
        })
    return rows


